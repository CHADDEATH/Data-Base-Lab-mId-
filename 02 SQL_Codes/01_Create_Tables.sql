-- Drop existing tables in reverse dependency order if recreating
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'REVIEWS', 'TRIP_EXPENSES', 'PAYMENTS', 'HOTEL_BOOKING_DETAILS', 
        'BOOKINGS', 'TRIP_CHECKLIST', 'TRIP_ITINERARY', 'TRIP_DESTINATIONS', 
        'TRIPS', 'PUBLIC_TRANSPORT_STOPS', 'PUBLIC_TRANSPORT_ROUTES', 
        'TRANSPORT_SERVICES', 'TRANSPORT_TYPES', 'FOOD_ITEMS', 'RESTAURANTS', 
        'FACILITY_TICKETS', 'ZOOS_PARKS', 'ACTIVITIES', 'TRAIL_SERVICES', 
        'TRAILS', 'LANDMARKS', 'HOTEL_FACILITIES', 'HOTEL_ROOMS', 'HOTELS', 
        'DESTINATION_GUIDES', 'DESTINATIONS', 'ADMIN_USERS', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
