-- 1. DESTINATION ATTRACTIONS AND INVENTORY SUMMARY VIEW
CREATE OR REPLACE VIEW VW_DESTINATION_SUMMARY AS
SELECT 
    d.DESTINATION_ID,
    d.DESTINATION_NAME,
    d.PROVINCE_REGION,
    d.BEST_TIME_TO_VISIT,
    (SELECT COUNT(*) FROM HOTELS h WHERE h.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_HOTELS,
    (SELECT COUNT(*) FROM LANDMARKS l WHERE l.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_LANDMARKS,
    (SELECT COUNT(*) FROM TRAILS t WHERE t.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_TRAILS,
    (SELECT COUNT(*) FROM ACTIVITIES a WHERE a.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_ACTIVITIES,
    (SELECT COUNT(*) FROM ZOOS_PARKS z WHERE z.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_ZOOS_PARKS,
    (SELECT COUNT(*) FROM RESTAURANTS r WHERE r.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_RESTAURANTS,
    (SELECT COUNT(*) FROM TRANSPORT_SERVICES ts WHERE ts.DESTINATION_ID = d.DESTINATION_ID) AS TOTAL_TRANSPORT_SERVICES,
    d.STATUS
FROM DESTINATIONS d;

-- 2. HOTEL CATALOG WITH ROOM PRICING RANGE VIEW
CREATE OR REPLACE VIEW VW_HOTEL_CATALOG AS
SELECT 
    h.HOTEL_ID,
    d.DESTINATION_NAME,
    h.HOTEL_NAME,
    h.CATEGORY,
    h.ADDRESS,
    h.CONTACT_PHONE,
    h.RATING,
    h.PRICE_PER_NIGHT_BASE,
    MIN(r.PRICE_PER_NIGHT) AS MIN_ROOM_PRICE,
    MAX(r.PRICE_PER_NIGHT) AS MAX_ROOM_PRICE,
    COUNT(r.ROOM_ID) AS ROOM_TYPES_COUNT,
    (SELECT COUNT(*) FROM HOTEL_FACILITIES f WHERE f.HOTEL_ID = h.HOTEL_ID AND f.IS_AVAILABLE = 'YES') AS FACILITIES_COUNT,
    h.STATUS
FROM HOTELS h
JOIN DESTINATIONS d ON h.DESTINATION_ID = d.DESTINATION_ID
LEFT JOIN HOTEL_ROOMS r ON h.HOTEL_ID = r.HOTEL_ID
GROUP BY 
    h.HOTEL_ID, d.DESTINATION_NAME, h.HOTEL_NAME, h.CATEGORY, 
    h.ADDRESS, h.CONTACT_PHONE, h.RATING, h.PRICE_PER_NIGHT_BASE, h.STATUS;

-- 3. TRAILS AND EXPEDITIONS DETAILED VIEW
CREATE OR REPLACE VIEW VW_TRAILS_DETAILED AS
SELECT 
    t.TRAIL_ID,
    d.DESTINATION_NAME,
    t.DISTRICT,
    t.TRAIL_NAME,
    t.TRAIL_CODE,
    t.STARTING_POINT,
    t.ENDING_POINT,
    t.DISTANCE_KM,
    t.DURATION_TEXT,
    t.DIFFICULTY_LEVEL,
    t.MIN_ALTITUDE_M,
    t.MAX_ALTITUDE_M,
    t.BEST_SEASON,
    t.GUIDE_REQUIRED,
    t.PORTER_RECOMMENDED,
    t.PERMIT_REQUIRED,
    t.BASE_ENTRY_FEE_PKR,
    (SELECT COUNT(*) FROM TRAIL_SERVICES ts WHERE ts.TRAIL_ID = t.TRAIL_ID) AS AVAILABLE_SERVICES_COUNT,
    (SELECT NVL(SUM(ts.COST_PKR), 0) FROM TRAIL_SERVICES ts WHERE ts.TRAIL_ID = t.TRAIL_ID AND ts.IS_MANDATORY = 'YES') AS MANDATORY_EXTRA_COST_PKR
FROM TRAILS t
JOIN DESTINATIONS d ON t.DESTINATION_ID = d.DESTINATION_ID;

-- 4. USER TRIPS COMPLETE OVERVIEW VIEW
CREATE OR REPLACE VIEW VW_USER_TRIP_SUMMARY AS
SELECT 
    t.TRIP_ID,
    u.USER_ID,
    u.USERNAME,
    u.FULL_NAME AS TOURIST_NAME,
    t.TRIP_NAME,
    t.START_DATE,
    t.END_DATE,
    (t.END_DATE - t.START_DATE + 1) AS DURATION_DAYS,
    t.NUM_TRAVELLERS,
    t.BUDGET_PKR,
    t.STATUS AS TRIP_STATUS,
    (SELECT COUNT(DISTINCT td.DESTINATION_ID) FROM TRIP_DESTINATIONS td WHERE td.TRIP_ID = t.TRIP_ID) AS DESTINATIONS_COUNT,
    (SELECT COUNT(*) FROM TRIP_ITINERARY ti WHERE ti.TRIP_ID = t.TRIP_ID) AS ITINERARY_ITEMS_COUNT,
    (SELECT NVL(SUM(b.TOTAL_COST_PKR), 0) FROM BOOKINGS b WHERE b.TRIP_ID = t.TRIP_ID AND b.BOOKING_STATUS != 'Cancelled') AS CONFIRMED_BOOKINGS_VAL_PKR,
    (SELECT NVL(SUM(te.AMOUNT_PKR), 0) FROM TRIP_EXPENSES te WHERE te.TRIP_ID = t.TRIP_ID) AS RECORDED_EXPENSES_PKR
FROM TRIPS t
JOIN USERS u ON t.USER_ID = u.USER_ID;

-- 5. DETAILED BOOKINGS MASTER VIEW
CREATE OR REPLACE VIEW VW_BOOKINGS_DETAILED AS
SELECT 
    b.BOOKING_ID,
    b.BOOKING_REF,
    u.USER_ID,
    u.FULL_NAME AS CUSTOMER_NAME,
    u.EMAIL AS CUSTOMER_EMAIL,
    u.CONTACT_PHONE_REPRESENTATION,
    t.TRIP_NAME,
    b.SERVICE_TYPE,
    b.SERVICE_REF_ID,
    b.BOOKING_DATE,
    b.TRAVEL_DATE,
    b.QUANTITY,
    b.UNIT_PRICE_PKR,
    b.TOTAL_COST_PKR,
    b.BOOKING_STATUS,
    b.PAYMENT_STATUS,
    (SELECT NVL(SUM(p.AMOUNT_PKR), 0) FROM PAYMENTS p WHERE p.BOOKING_ID = b.BOOKING_ID) AS AMOUNT_PAID_PKR
FROM BOOKINGS b
JOIN USERS u ON b.USER_ID = u.USER_ID
LEFT JOIN TRIPS t ON b.TRIP_ID = t.TRIP_ID;

-- 6. RESTAURANT AND LOCAL GASTRONOMY SPECIALTIES VIEW
CREATE OR REPLACE VIEW VW_RESTAURANT_SPECIALTIES AS
SELECT 
    r.RESTAURANT_ID,
    d.DESTINATION_NAME,
    r.RESTAURANT_NAME,
    r.FOOD_AREA,
    r.CUISINE_TYPE,
    r.PRICE_CATEGORY,
    r.RATING,
    COUNT(f.ITEM_ID) AS TOTAL_MENU_ITEMS,
    SUM(CASE WHEN f.IS_LOCAL_SPECIALTY = 'YES' THEN 1 ELSE 0 END) AS LOCAL_SPECIALTY_COUNT,
    MIN(f.PRICE_PKR) AS MIN_DISH_PRICE,
    MAX(f.PRICE_PKR) AS MAX_DISH_PRICE
FROM RESTAURANTS r
JOIN DESTINATIONS d ON r.DESTINATION_ID = d.DESTINATION_ID
LEFT JOIN FOOD_ITEMS f ON r.RESTAURANT_ID = f.RESTAURANT_ID
GROUP BY 
    r.RESTAURANT_ID, d.DESTINATION_NAME, r.RESTAURANT_NAME, 
    r.FOOD_AREA, r.CUISINE_TYPE, r.PRICE_CATEGORY, r.RATING;

-- 7. PUBLIC TRANSIT NETWORK VIEW
CREATE OR REPLACE VIEW VW_PUBLIC_TRANSIT_NETWORK AS
SELECT 
    r.ROUTE_ID,
    d.DESTINATION_NAME,
    ts.SERVICE_NAME,
    tt.TYPE_NAME AS VEHICLE_TYPE,
    r.ROUTE_NAME,
    r.START_STOP,
    r.END_STOP,
    r.TOTAL_DISTANCE_KM,
    r.FARE_PKR,
    r.OPERATING_HOURS,
    COUNT(s.STOP_ID) AS TOTAL_STOPS_COUNT
FROM PUBLIC_TRANSPORT_ROUTES r
JOIN DESTINATIONS d ON r.DESTINATION_ID = d.DESTINATION_ID
JOIN TRANSPORT_SERVICES ts ON r.SERVICE_ID = ts.SERVICE_ID
JOIN TRANSPORT_TYPES tt ON ts.TRANSPORT_TYPE_ID = tt.TRANSPORT_TYPE_ID
LEFT JOIN PUBLIC_TRANSPORT_STOPS s ON r.ROUTE_ID = s.ROUTE_ID
GROUP BY 
    r.ROUTE_ID, d.DESTINATION_NAME, ts.SERVICE_NAME, tt.TYPE_NAME,
    r.ROUTE_NAME, r.START_STOP, r.END_STOP, r.TOTAL_DISTANCE_KM, 
    r.FARE_PKR, r.OPERATING_HOURS;

COMMIT;
