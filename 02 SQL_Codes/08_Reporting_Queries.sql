-- 1. EXECUTIVE KPI DASHBOARD SUMMARY
SELECT 
    (SELECT COUNT(*) FROM USERS WHERE STATUS = 'ACTIVE') AS ACTIVE_REGISTERED_USERS,
    (SELECT COUNT(*) FROM TRIPS) AS TOTAL_TRIPS_PLANNED,
    (SELECT COUNT(*) FROM BOOKINGS) AS TOTAL_BOOKINGS_COUNT,
    (SELECT COUNT(*) FROM BOOKINGS WHERE BOOKING_STATUS = 'Confirmed') AS CONFIRMED_BOOKINGS,
    (SELECT COUNT(*) FROM BOOKINGS WHERE BOOKING_STATUS = 'Cancelled') AS CANCELLED_BOOKINGS,
    (SELECT NVL(SUM(TOTAL_COST_PKR), 0) FROM BOOKINGS WHERE BOOKING_STATUS != 'Cancelled') AS ESTIMATED_GROSS_BOOKING_VAL,
    (SELECT NVL(SUM(AMOUNT_PKR), 0) FROM PAYMENTS WHERE PAYMENT_STATUS = 'Recorded') AS RECORDED_PAYMENT_COLLECTION,
    (SELECT NVL(ROUND(AVG(BUDGET_PKR), 2), 0) FROM TRIPS) AS AVERAGE_TRIP_BUDGET
FROM DUAL;

-- 2. DESTINATION POPULARITY MATRIX (TRIPS AND ATTRACTIONS)
SELECT 
    d.DESTINATION_ID,
    d.DESTINATION_NAME,
    d.PROVINCE_REGION,
    COUNT(DISTINCT td.TRIP_ID) AS TIMES_SELECTED_IN_TRIPS,
    (SELECT COUNT(*) FROM HOTELS h WHERE h.DESTINATION_ID = d.DESTINATION_ID) AS AVAILABLE_HOTELS,
    (SELECT COUNT(*) FROM LANDMARKS l WHERE l.DESTINATION_ID = d.DESTINATION_ID) AS VERIFIED_LANDMARKS,
    (SELECT COUNT(*) FROM TRAILS t WHERE t.DESTINATION_ID = d.DESTINATION_ID) AS HIKING_TRAILS,
    (SELECT COUNT(*) FROM ACTIVITIES a WHERE a.DESTINATION_ID = d.DESTINATION_ID) AS ADVENTURE_ACTIVITIES
FROM DESTINATIONS d
LEFT JOIN TRIP_DESTINATIONS td ON d.DESTINATION_ID = td.DESTINATION_ID
GROUP BY d.DESTINATION_ID, d.DESTINATION_NAME, d.PROVINCE_REGION
ORDER BY TIMES_SELECTED_IN_TRIPS DESC, d.DESTINATION_NAME;

-- 3. HOTEL PRICING AND CATEGORY ANALYSIS
SELECT 
    CATEGORY AS HOTEL_CATEGORY,
    COUNT(HOTEL_ID) AS TOTAL_PROPERTIES,
    ROUND(AVG(PRICE_PER_NIGHT_BASE), 2) AS AVG_BASE_PRICE_PKR,
    MIN(PRICE_PER_NIGHT_BASE) AS LOWEST_NIGHT_PRICE_PKR,
    MAX(PRICE_PER_NIGHT_BASE) AS HIGHEST_NIGHT_PRICE_PKR,
    ROUND(AVG(RATING), 2) AS AVERAGE_RATING
FROM HOTELS
GROUP BY CATEGORY
ORDER BY AVG_BASE_PRICE_PKR DESC;

-- 4. TREKKING AND HIKING DIFFICULTY BREAKDOWN
SELECT 
    DIFFICULTY_LEVEL,
    COUNT(TRAIL_ID) AS NUMBER_OF_TRAILS,
    ROUND(AVG(DISTANCE_KM), 2) AS AVG_DISTANCE_KM,
    ROUND(AVG(NVL(MAX_ALTITUDE_M, 0)), 0) AS AVG_MAX_ALTITUDE_M,
    SUM(CASE WHEN GUIDE_REQUIRED = 'YES' THEN 1 ELSE 0 END) AS REQUIRES_GUIDE_COUNT,
    SUM(CASE WHEN PERMIT_REQUIRED = 'YES' THEN 1 ELSE 0 END) AS REQUIRES_PERMIT_COUNT
FROM TRAILS
GROUP BY DIFFICULTY_LEVEL
ORDER BY 
    CASE DIFFICULTY_LEVEL 
        WHEN 'Easy' THEN 1 
        WHEN 'Moderate' THEN 2 
        WHEN 'Difficult' THEN 3 
        WHEN 'Extreme' THEN 4 
    END;

-- 5. ADVENTURE ACTIVITIES BY PRICING MODEL AND DESTINATION
SELECT 
    d.DESTINATION_NAME,
    a.PRICING_MODEL,
    COUNT(a.ACTIVITY_ID) AS ACTIVITY_COUNT,
    ROUND(AVG(a.PRICE_PKR), 2) AS AVERAGE_PRICE_PKR,
    MIN(a.PRICE_PKR) AS MIN_PRICE_PKR,
    MAX(a.PRICE_PKR) AS MAX_PRICE_PKR
FROM ACTIVITIES a
JOIN DESTINATIONS d ON a.DESTINATION_ID = d.DESTINATION_ID
GROUP BY d.DESTINATION_NAME, a.PRICING_MODEL
HAVING COUNT(a.ACTIVITY_ID) >= 1
ORDER BY d.DESTINATION_NAME, a.PRICING_MODEL;

-- 6. MONTHLY BOOKING AND REVENUE VELOCITY
SELECT 
    TO_CHAR(BOOKING_DATE, 'YYYY-MM') AS BOOKING_MONTH,
    COUNT(BOOKING_ID) AS TOTAL_BOOKINGS,
    SUM(CASE WHEN BOOKING_STATUS = 'Confirmed' THEN 1 ELSE 0 END) AS CONFIRMED_COUNT,
    SUM(CASE WHEN BOOKING_STATUS = 'Cancelled' THEN 1 ELSE 0 END) AS CANCELLED_COUNT,
    ROUND(SUM(TOTAL_COST_PKR), 2) AS GROSS_BOOKING_VALUE_PKR,
    ROUND(AVG(TOTAL_COST_PKR), 2) AS AVERAGE_BOOKING_SIZE_PKR
FROM BOOKINGS
GROUP BY TO_CHAR(BOOKING_DATE, 'YYYY-MM')
ORDER BY BOOKING_MONTH DESC;

-- 7. TOP REGISTERED USERS BY TRAVEL ENGAGEMENT
SELECT 
    u.USER_ID,
    u.USERNAME,
    u.FULL_NAME,
    u.COUNTRY,
    COUNT(DISTINCT t.TRIP_ID) AS TOTAL_TRIPS_CREATED,
    COUNT(DISTINCT b.BOOKING_ID) AS TOTAL_BOOKINGS_MADE,
    NVL(SUM(b.TOTAL_COST_PKR), 0) AS CUMULATIVE_BOOKING_VALUE_PKR,
    NVL(SUM(p.AMOUNT_PKR), 0) AS TOTAL_PAYMENTS_DEPOSITED
FROM USERS u
LEFT JOIN TRIPS t ON u.USER_ID = t.USER_ID
LEFT JOIN BOOKINGS b ON u.USER_ID = b.USER_ID AND b.BOOKING_STATUS != 'Cancelled'
LEFT JOIN PAYMENTS p ON b.BOOKING_ID = p.BOOKING_ID
GROUP BY u.USER_ID, u.USERNAME, u.FULL_NAME, u.COUNTRY
HAVING COUNT(DISTINCT t.TRIP_ID) > 0 OR COUNT(DISTINCT b.BOOKING_ID) > 0
ORDER BY CUMULATIVE_BOOKING_VALUE_PKR DESC;

-- 8. TRIP BUDGET OVERRUN / SURPLUS AUDIT
SELECT 
    t.TRIP_ID,
    u.USERNAME,
    t.TRIP_NAME,
    t.BUDGET_PKR AS PLANNED_BUDGET,
    NVL(SUM(te.AMOUNT_PKR), 0) AS RECORDED_EXPENSES,
    (t.BUDGET_PKR - NVL(SUM(te.AMOUNT_PKR), 0)) AS REMAINING_BUDGET,
    CASE 
        WHEN NVL(SUM(te.AMOUNT_PKR), 0) > t.BUDGET_PKR THEN 'OVER BUDGET'
        WHEN NVL(SUM(te.AMOUNT_PKR), 0) >= (t.BUDGET_PKR * 0.85) THEN 'NEAR LIMIT'
        ELSE 'WITHIN BUDGET'
    END AS BUDGET_HEALTH_STATUS
FROM TRIPS t
JOIN USERS u ON t.USER_ID = u.USER_ID
LEFT JOIN TRIP_EXPENSES te ON t.TRIP_ID = te.TRIP_ID
GROUP BY t.TRIP_ID, u.USERNAME, t.TRIP_NAME, t.BUDGET_PKR
ORDER BY REMAINING_BUDGET ASC;

-- 9. RESTAURANTS WITH LOCAL REGIONAL SPECIALTIES
SELECT 
    d.DESTINATION_NAME,
    r.RESTAURANT_NAME,
    r.CUISINE_TYPE,
    r.PRICE_CATEGORY,
    f.ITEM_NAME AS SPECIALTY_DISH,
    f.PRICE_PKR AS DISH_PRICE_PKR
FROM RESTAURANTS r
JOIN DESTINATIONS d ON r.DESTINATION_ID = d.DESTINATION_ID
JOIN FOOD_ITEMS f ON r.RESTAURANT_ID = f.RESTAURANT_ID
WHERE f.IS_LOCAL_SPECIALTY = 'YES'
ORDER BY d.DESTINATION_NAME, r.RESTAURANT_NAME;

