-- 1. TRIGGER: PREVENT DUPLICATE ACTIVE BOOKINGS
-- Ensures a user cannot book the identical service on the exact same travel date twice
CREATE OR REPLACE TRIGGER TRG_PREVENT_DUP_BOOKING
BEFORE INSERT ON BOOKINGS
FOR EACH ROW
DECLARE
    v_existing_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existing_count
    FROM BOOKINGS
    WHERE USER_ID = :NEW.USER_ID
      AND SERVICE_TYPE = :NEW.SERVICE_TYPE
      AND SERVICE_REF_ID = :NEW.SERVICE_REF_ID
      AND TRUNC(TRAVEL_DATE) = TRUNC(:NEW.TRAVEL_DATE)
      AND BOOKING_STATUS IN ('Confirmed', 'Pending');

    IF v_existing_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'DUPLICATE BOOKING ERROR: You already have an active booking for this service on the selected date.');
    END IF;
END;
/

-- 2. TRIGGER: AUTO-SYNC PAYMENT STATUS ON NEW PAYMENT
CREATE OR REPLACE TRIGGER TRG_SYNC_PAYMENT_STATUS
AFTER INSERT ON PAYMENTS
FOR EACH ROW
DECLARE
    v_total_paid NUMBER;
    v_booking_cost NUMBER;
BEGIN
    SELECT NVL(SUM(AMOUNT_PKR), 0) INTO v_total_paid
    FROM PAYMENTS
    WHERE BOOKING_ID = :NEW.BOOKING_ID;

    SELECT TOTAL_COST_PKR INTO v_booking_cost
    FROM BOOKINGS
    WHERE BOOKING_ID = :NEW.BOOKING_ID;

    IF v_total_paid >= v_booking_cost THEN
        UPDATE BOOKINGS
        SET PAYMENT_STATUS = 'Paid'
        WHERE BOOKING_ID = :NEW.BOOKING_ID;
    END IF;
END;
/

-- 3. TRIGGER: AUTOMATIC TRIP STATUS ADJUSTMENT
-- Marks trip 'COMPLETED' if end_date has passed and status is still 'PLANNED'
CREATE OR REPLACE TRIGGER TRG_TRIP_STATUS_SYNC
BEFORE INSERT OR UPDATE OF START_DATE, END_DATE ON TRIPS
FOR EACH ROW
BEGIN
    IF :NEW.END_DATE < TRUNC(SYSDATE) AND :NEW.STATUS = 'PLANNED' THEN
        :NEW.STATUS := 'COMPLETED';
    END IF;
END;
/

-- 4. TRIGGER: AUDIT LOG ON ADMIN USER CREATION
CREATE OR REPLACE TRIGGER TRG_ADMIN_TIMESTAMP
BEFORE INSERT ON ADMIN_USERS
FOR EACH ROW
BEGIN
    :NEW.CREATED_AT := SYSDATE;
END;
/

