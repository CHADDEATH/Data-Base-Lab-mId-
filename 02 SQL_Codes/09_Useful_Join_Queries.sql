-- 1. TWO-TABLE INNER JOIN: HOTELS AND THEIR DESTINATIONS
-- Demonstrates primary-foreign key relationship navigation
SELECT 
    h.HOTEL_NAME,
    h.CATEGORY,
    h.PRICE_PER_NIGHT_BASE,
    d.DESTINATION_NAME,
    d.PROVINCE_REGION
FROM HOTELS h
INNER JOIN DESTINATIONS d ON h.DESTINATION_ID = d.DESTINATION_ID
WHERE h.STATUS = 'ACTIVE'
ORDER BY d.DESTINATION_NAME, h.PRICE_PER_NIGHT_BASE ASC;

-- 2. THREE-TABLE JOIN: HOTEL ROOMS, HOTELS AND DESTINATIONS
-- Demonstrates multi-level hierarchy retrieval
SELECT 
    d.DESTINATION_NAME,
    h.HOTEL_NAME,
    r.ROOM_TYPE,
    r.BED_CONFIG,
    r.PRICE_PER_NIGHT,
    r.BREAKFAST_INCLUDED,
    r.DINNER_INCLUDED
FROM HOTEL_ROOMS r
INNER JOIN HOTELS h ON r.HOTEL_ID = h.HOTEL_ID
INNER JOIN DESTINATIONS d ON h.DESTINATION_ID = d.DESTINATION_ID
WHERE r.BREAKFAST_INCLUDED = 'YES'
ORDER BY r.PRICE_PER_NIGHT ASC;

-- 3. FOUR-TABLE JOIN: PUBLIC TRANSIT NETWORK (STOPS -> ROUTES -> SERVICES -> TYPES)
SELECT 
    s.STOP_SEQUENCE,
    s.STOP_NAME,
    s.NEARBY_LANDMARK,
    r.ROUTE_NAME,
    r.FARE_PKR,
    ts.SERVICE_NAME AS OPERATOR_SERVICE,
    tt.TYPE_NAME AS VEHICLE_TYPE
FROM PUBLIC_TRANSPORT_STOPS s
JOIN PUBLIC_TRANSPORT_ROUTES r ON s.ROUTE_ID = r.ROUTE_ID
JOIN TRANSPORT_SERVICES ts ON r.SERVICE_ID = ts.SERVICE_ID
JOIN TRANSPORT_TYPES tt ON ts.TRANSPORT_TYPE_ID = tt.TRANSPORT_TYPE_ID
WHERE r.ROUTE_ID = 1
ORDER BY s.STOP_SEQUENCE ASC;

-- 4. LEFT OUTER JOIN: ALL TRAILS WITH OPTIONAL MANDATORY SERVICES
-- Demonstrates displaying parent rows even when child records do not exist
SELECT 
    t.TRAIL_NAME,
    t.DIFFICULTY_LEVEL,
    t.BASE_ENTRY_FEE_PKR,
    ts.SERVICE_NAME,
    ts.SERVICE_TYPE,
    ts.COST_PKR,
    ts.IS_MANDATORY
FROM TRAILS t
LEFT OUTER JOIN TRAIL_SERVICES ts ON t.TRAIL_ID = ts.TRAIL_ID AND ts.IS_MANDATORY = 'YES'
WHERE t.DESTINATION_ID IN (4, 5) -- Skardu AND Kashmir
ORDER BY t.TRAIL_NAME;

-- 5. CORRELATED SUBQUERY: HOTELS PRICED ABOVE REGIONAL AVERAGE
-- Finds properties with nightly rates higher than the average in that destination
SELECT 
    h1.HOTEL_NAME,
    h1.CATEGORY,
    h1.PRICE_PER_NIGHT_BASE,
    d.DESTINATION_NAME
FROM HOTELS h1
JOIN DESTINATIONS d ON h1.DESTINATION_ID = d.DESTINATION_ID
WHERE h1.PRICE_PER_NIGHT_BASE > (
    SELECT AVG(h2.PRICE_PER_NIGHT_BASE)
    FROM HOTELS h2
    WHERE h2.DESTINATION_ID = h1.DESTINATION_ID
)
ORDER BY d.DESTINATION_NAME, h1.PRICE_PER_NIGHT_BASE DESC;

-- 6. EXISTS CLAUSE: DESTINATIONS WITH HIGH-ALTITUDE TREKS (>3000M)
SELECT 
    d.DESTINATION_ID,
    d.DESTINATION_NAME,
    d.PROVINCE_REGION
FROM DESTINATIONS d
WHERE EXISTS (
    SELECT 1 
    FROM TRAILS t 
    WHERE t.DESTINATION_ID = d.DESTINATION_ID 
      AND t.MAX_ALTITUDE_M >= 3000
);

-- 7. NOT EXISTS: USERS WHO HAVE NEVER CANCELLED A BOOKING
SELECT 
    u.USER_ID,
    u.USERNAME,
    u.FULL_NAME,
    u.EMAIL
FROM USERS u
WHERE EXISTS (
    SELECT 1 FROM BOOKINGS b WHERE b.USER_ID = u.USER_ID
) AND NOT EXISTS (
    SELECT 1 FROM BOOKINGS b WHERE b.USER_ID = u.USER_ID AND b.BOOKING_STATUS = 'Cancelled'
);

-- 8. GROUP BY AND HAVING: RESTAURANTS OFFERING 2 OR MORE SPECIALTY DISHES
SELECT 
    r.RESTAURANT_NAME,
    r.FOOD_AREA,
    d.DESTINATION_NAME,
    COUNT(f.ITEM_ID) AS SPECIALTY_COUNT,
    ROUND(AVG(f.PRICE_PKR), 2) AS AVG_SPECIALTY_PRICE
FROM RESTAURANTS r
JOIN DESTINATIONS d ON r.DESTINATION_ID = d.DESTINATION_ID
JOIN FOOD_ITEMS f ON r.RESTAURANT_ID = f.RESTAURANT_ID
WHERE f.IS_LOCAL_SPECIALTY = 'YES'
GROUP BY r.RESTAURANT_NAME, r.FOOD_AREA, d.DESTINATION_NAME
HAVING COUNT(f.ITEM_ID) >= 2
ORDER BY SPECIALTY_COUNT DESC;

-- 9. SET OPERATION (UNION): ALL VERIFIED VISITABLE LOCATIONS IN ISLAMABAD
-- Combines Landmarks and Zoos/Parks into a single unified catalog
SELECT 
    LANDMARK_NAME AS ATTRACTION_NAME, 
    CATEGORY AS ATTRACTION_TYPE, 
    LOCATION_ADDRESS AS ADDRESS,
    ENTRY_FEE_ADULT_PKR AS ADULT_ENTRY_PKR
FROM LANDMARKS
WHERE DESTINATION_ID = 1
UNION
SELECT 
    FACILITY_NAME AS ATTRACTION_NAME, 
    FACILITY_TYPE AS ATTRACTION_TYPE, 
    ADDRESS AS ADDRESS,
    ADULT_TICKET_PKR AS ADULT_ENTRY_PKR
FROM ZOOS_PARKS
WHERE DESTINATION_ID = 1
ORDER BY ATTRACTION_NAME;
